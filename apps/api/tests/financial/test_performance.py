def explain_nested(conn: Connection, sql: str, params: dict[str, Any]) -> tuple[str, float]:
    """Run `sql` and return (the plans of every statement it ran, seconds), read from the server."""
    messages: list[str] = []
    raw: Any = conn.connection.dbapi_connection
    raw.add_notice_handler(lambda diag: messages.append(str(diag.message_primary)))
    conn.exec_driver_sql("LOAD 'auto_explain'")
    conn.exec_driver_sql("SET auto_explain.log_min_duration = 0")
    conn.exec_driver_sql("SET auto_explain.log_nested_statements = on")
    conn.exec_driver_sql("SET client_min_messages = log")
    started = time.perf_counter()
    result = conn.execute(text(sql), params)
    if result.returns_rows:
        result.all()
    elapsed = time.perf_counter() - started
    conn.exec_driver_sql("SET client_min_messages = notice")
    return "\n".join(messages), elapsed


def assert_indexed(plans: str) -> None:
    assert "plan:" in plans, "no plan was captured: auto_explain did not report"
    assert "Seq Scan on financial_transactions" not in plans, plans
    assert "Seq Scan on expenses" not in plans, plans
    for detail in ("contributions", "reimbursements", "refunds"):
        assert f"Seq Scan on {detail}" not in plans, plans
    assert (
        "ix_financial_transactions_school_settled" in plans
        or "ix_financial_transactions_school_status" in plans
    ), plans


def test_the_data_set_has_a_hundred_thousand_movements(perf: PerfData) -> None:
    with perf.engine.connect() as conn:
        assert (
            conn.execute(
                text("SELECT count(*) FROM financial_transactions WHERE organization_id = :o"),
                {"o": perf.org},
            ).scalar_one()
            == TOTAL
        )
        assert (
            conn.execute(
                text(
                    "SELECT count(DISTINCT school_id) FROM financial_transactions WHERE organization_id = :o"
                ),
                {"o": perf.org},
            ).scalar_one()
            == SCHOOLS
        )


@pytest.mark.parametrize(
    ("name", "sql", "seconds"),
    [
        (
            "entries of a month",
            "SELECT * FROM statement_entries(:s, '2025-03-01', '2025-03-31')",
            1.0,
        ),
        (
            "summary of a month",
            "SELECT * FROM statement_summary(:s, '2025-03-01', '2025-03-31')",
            1.0,
        ),
        (
            "summary of the last month with an old opening",
            "SELECT * FROM statement_summary(:s, '2025-11-01', '2025-11-30')",
            1.0,
        ),
        ("hash of a month", "SELECT closing_entries_hash(:s, '2025-03-01', '2025-03-31')", 2.0),
        ("pending", "SELECT * FROM statement_pending(:s)", 1.0),
    ],
)
def test_the_statement_uses_the_index_and_is_fast(
    perf: PerfData, name: str, sql: str, seconds: float
) -> None:
    with perf.engine.connect() as conn:
        plans, elapsed = explain_nested(conn, sql, {"s": perf.schools[0]})
    assert_indexed(plans)
    print(f"PERF {name}: {elapsed * 1000:.1f} ms")
    assert elapsed < seconds, f"{name} took {elapsed:.2f}s"


def test_closing_a_month_uses_the_index_and_is_fast(perf: PerfData) -> None:
    with perf.engine.connect() as conn:
        transaction = conn.begin()
        plans, elapsed = explain_nested(
            conn,
            "INSERT INTO monthly_closings (organization_id, school_id, period_start, closed_by_user_id) "
            "VALUES (:o, :s, '2024-02-01', :u)",
            {"o": perf.org, "s": perf.schools[1], "u": perf.user},
        )
        transaction.rollback()
    assert_indexed(plans)
    print(f"PERF closing a month: {elapsed * 1000:.1f} ms")
    assert elapsed < 3.0, f"closing took {elapsed:.2f}s"


def test_the_reference_code_lookup_and_the_booking_use_indexes(perf: PerfData) -> None:
    """max(reference_code) walks the (school_id, reference_code) index; the booking reads the closings by school."""
    with perf.engine.connect() as conn:
        transaction = conn.begin()
        plans, elapsed = explain_nested(
            conn,
            "INSERT INTO financial_transactions (organization_id, school_id, kind, direction, amount_cents, "
            "status, category_id, origin_type) VALUES (:o, :s, 'CONTRIBUTION', 'IN', 100, "
            "'PENDING_PAYMENT', (SELECT id FROM categories WHERE school_id = :s AND key = 'perf_in'), 'GUARDIAN')",
            {"o": perf.org, "s": perf.schools[2]},
        )
        transaction.rollback()
    assert "Seq Scan on financial_transactions" not in plans, plans
    assert "uq_financial_transactions_school_id_reference_code" in plans, plans
    assert elapsed < 1.0
