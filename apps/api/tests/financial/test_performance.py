"""Condition 7: with about 100 thousand movements the statement and the closing use the index.

The data is generated by SQL in the throwaway database of the session (never the development one):
20 schools of 5 thousand movements over two years (contributions, expenses of the APM and of
collaborators, reimbursements, refunds). The plans are read from the server itself with
auto_explain (nested statements, because the statement functions hide their query), and a plan with
a sequential scan of the ledger or of the expenses fails the test.
"""

